KNOWN_OPTIMA = {e[0]: {"with_transfer": (2, OPT_WITH_TRANSFER_DIST), "without_transfer": e[8]}
                for e in _E}


def instance(name: str, fleet_size: int = 4, allow_transfer: bool = True) -> Instance:
    e = next(x for x in _E if x[0] == name)
    _, n, pk, dl, loads, Q, bi_p, bi_d, _ = e
    nodes = {"depot": Node("depot", 0.0, 0.0, 0.0, 566.0, 0.0),
             "t": Node("t", 0.0, 0.0, 0.0, 566.0, 0.0)}
    requests = {}
    for i in range(n):
        p, d = f"c{i+1}", f"c{i+1+n}"
        nodes[p] = Node(p, float(pk[i][0]), float(pk[i][1]), 0.0, float(bi_p[i]), 0.0)
        nodes[d] = Node(d, float(dl[i][0]), float(dl[i][1]), 0.0, float(bi_d[i]), 0.0)
        requests[f"r{i+1}"] = Request(f"r{i+1}", p, d, float(loads[i]))
    tps = {"t": TransferPoint("t", "t")} if allow_transfer else {}
    vehicles = {f"k{j+1}": Vehicle(f"k{j+1}", float(Q), "depot", "depot") for j in range(fleet_size)}
    inst = Instance(name=f"TT14-{name}", nodes=nodes, requests=requests, transfer_points=tps,
                    vehicles=vehicles, params=Params(speed=1.0, max_transfers_per_request=1),
                    meta={"source": "Tchapnga Takoudjou 2014, Appendix A.2 and Table 3.4",
                          "known_optimum": KNOWN_OPTIMA[name]})
    inst.validate()
    return inst


def all_instances(**kw) -> list[Instance]:
    return [instance(e[0], **kw) for e in _E]
